from abc import ABC, abstractmethod


class AIGuide(ABC):

    @abstractmethod
    def generate_guide(self, vehicle, task, specifications):
        pass


class MockAIGuide(AIGuide):

    def generate_guide(self, vehicle, task, specifications):

        vehicle_name = (
            f"{vehicle['make']} {vehicle['model']} "
            f"({vehicle['year']}) - {vehicle['engine']}"
        )

        guide = (
            f"Maintenance Overview: {task['name']}\n\n"
            f"Vehicle: {vehicle_name}\n\n"
            f"{task['description']}\n\n"
            "Safety Precautions:\n"
            "- Consult the official vehicle service manual.\n"
            "- Use appropriate protective equipment.\n"
            "- Ensure the vehicle is safely secured.\n\n"
        )

        if specifications:
            guide += (
                "Refer to the verified technical specifications "
                "displayed above.\n\n"
            )
        else:
            guide += (
                "Vehicle-specific specifications have not yet "
                "been verified. Do not proceed without "
                "consulting the official service manual.\n\n"
            )

        guide += (
            "This is a demonstration generated by the "
            "mock AI component, not a complete repair procedure."
        )

        return guide

if __name__ == "__main__":
    vehicle = {
        "make": "Opel",
        "model": "Astra",
        "year": 2015,
        "engine": "1.3 CDTI"
    }

    task = {
        "name": "Engine Oil Change",
        "description": "Replacing the engine oil and oil filter."
    }

    ai = MockAIGuide()

    print(ai.generate_guide(vehicle, task, []))